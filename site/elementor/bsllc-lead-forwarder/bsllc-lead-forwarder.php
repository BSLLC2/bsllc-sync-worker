const BSLLC_LF_OPTION        = 'bsllc_lead_forwarder';
const BSLLC_LF_REPLAY_OPTION = 'bsllc_lead_forwarder_replay';
const BSLLC_LF_BASE_URL      = 'https://work.bsllc.biz/api/webform/';
const BSLLC_LF_ATTRIB_COOKIE = 'bs_attrib';
