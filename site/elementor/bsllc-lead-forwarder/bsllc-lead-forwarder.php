const BSLLC_LF_REPLAY_BATCH  = 100;

function bsllc_lf_settings() {
	$o = get_option( BSLLC_LF_OPTION, array() );
	return array(
		'slug' => defined( 'BSLLC_CLIENT_SLUG' ) ? BSLLC_CLIENT_SLUG : ( isset( $o['slug'] ) ? trim( (string) $o['slug'] ) : '' ),
		'key'  => defined( 'BSLLC_WEBFORM_KEY' ) ? BSLLC_WEBFORM_KEY : ( isset( $o['key'] ) ? trim( (string) $o['key'] ) : '' ),
		'from' => isset( $o['from'] ) ? trim( (string) $o['from'] ) : '',
	);
}

/**
 * Normalises Elementor field records ([ id => [value, type, title] ]) into the
 * flat keys the dashboard's parser reads. Shared by the live hook and the
 * history replay, so both produce identical rows.
 */
function bsllc_lf_normalize( array $raw_fields ) {
	$norm     = array();
	$passthru = array();
	$fullname = '';

	foreach ( $raw_fields as $id => $f ) {
		$val = trim( (string) ( isset( $f['value'] ) ? $f['value'] : '' ) );
		if ( '' === $val ) {
			continue;
		}
		$type  = strtolower( isset( $f['type'] ) ? $f['type'] : '' );
		$label = strtolower( isset( $f['title'] ) ? $f['title'] : '' );
		$key   = strtolower( (string) $id );
		$hay   = $key . ' ' . $label;

		$passthru[ 'field_' . $key ] = $val;

		if ( 'email' === $type || false !== strpos( $hay, 'email' ) ) {
			if ( empty( $norm['email'] ) ) { $norm['email'] = $val; }
			continue;
		}
		if ( 'tel' === $type || preg_match( '/phone|tel|mobile|cell/', $hay ) ) {
			if ( empty( $norm['phone'] ) ) { $norm['phone'] = $val; }
			continue;
		}
		if ( preg_match( '/dob|birth/', $hay ) ) {
			if ( empty( $norm['dob'] ) ) { $norm['dob'] = $val; }
			continue;
		}
		if ( preg_match( '/^(gclid|gbraid|wbraid|utm_source|utm_medium|utm_campaign|utm_content|utm_term|landing_page)$/', $key ) ) {
			$norm[ $key ] = $val;
			continue;
		}
		if ( preg_match( '/first/', $hay ) ) {
			if ( empty( $norm['first_name'] ) ) { $norm['first_name'] = $val; }
			continue;
		}
		if ( preg_match( '/last|surname/', $hay ) ) {
			if ( empty( $norm['last_name'] ) ) { $norm['last_name'] = $val; }
			continue;
		}
		if ( preg_match( '/(^|\s)(full |your )?name$/', $label ) || 'name' === $key ) {
			if ( '' === $fullname ) { $fullname = $val; }
		}
	}

	if ( empty( $norm['first_name'] ) && '' !== $fullname ) {
		$parts              = preg_split( '/\s+/', $fullname, 2 );
		$norm['first_name'] = $parts[0];
		if ( ! empty( $parts[1] ) ) {
			$norm['last_name'] = $parts[1];
		}
	}
	return array( $norm, $passthru );
}

/** POSTs one normalised submission. Returns true on 2xx, else an error string. */
function bsllc_lf_post( array $data, $label ) {
	$s   = bsllc_lf_settings();
	$res = wp_remote_post(
		BSLLC_LF_BASE_URL . rawurlencode( $s['slug'] ) . '?key=' . rawurlencode( $s['key'] ),
		array(
			'timeout' => 5,
			'headers' => array( 'Content-Type' => 'application/json' ),
			'body'    => wp_json_encode( $data ),
		)
	);
	if ( is_wp_error( $res ) ) {
		$err = $res->get_error_message();
	} elseif ( wp_remote_retrieve_response_code( $res ) >= 300 ) {
		$err = 'HTTP ' . wp_remote_retrieve_response_code( $res ) . ' ' . substr( (string) wp_remote_retrieve_body( $res ), 0, 200 );
	} else {
		return true;
	}
	error_log( 'BSLLC webform POST failed [' . $label . ']: ' . $err );
	return $err;
}

